"""Build the DockQ reference for each target.

For every selected target this:
  1. downloads the RCSB FASTA and writes receptor / peptide / complex FASTA files
     (full construct sequences -- what the predictors should be given), and
  2. downloads coordinates, keeps exactly one receptor chain + one peptide chain
     (config `native_chains`), strips ligands/waters/alt-locs, and writes
     data/natives/<ID>_native.pdb  -- the file DockQ compares against.

Coordinate source:
  --source entry     (default) the deposited asymmetric unit  <ID>.cif
  --source assembly  the first biological assembly            <ID>-assembly1.cif
Use `entry` unless a target's notes say the biological receptor is generated by
crystal symmetry (e.g. 3QNJ / 4JW* / 6Y0*) -- then check `assembly`.

Runs on CPU, no GPU. Deps: gemmi, requests, pyyaml.
"""
from __future__ import annotations

import argparse
import csv
import sys
import time

import gemmi
import requests

from config import (NATIVES, RCSB_ASSEMBLY_CIF, RCSB_ENTRY_CIF, RCSB_FASTA,
                    SEQUENCES, load_targets, select)

UA = {"User-Agent": "epic-amp-benchmark/1.0 (academic)"}


def _get(url: str, tries: int = 4) -> str:
    for i in range(tries):
        r = requests.get(url, headers=UA, timeout=60)
        if r.ok:
            return r.text
        if r.status_code == 404:
            raise FileNotFoundError(url)
        time.sleep(2 * (i + 1))
    r.raise_for_status()
    return ""


def parse_rcsb_fasta(text: str) -> list[tuple[list[str], str]]:
    """-> [(auth_chain_ids, sequence), ...] one entry per polymer entity."""
    out, chains, seq = [], None, []
    for line in text.splitlines():
        if line.startswith(">"):
            if chains is not None:
                out.append((chains, "".join(seq)))
            seq = []
            # header: >6HY2_1|Chains X|name|organism   or  |Chain A|
            parts = line.split("|")
            chunk = parts[1] if len(parts) > 1 else ""
            chunk = chunk.replace("Chains", "").replace("Chain", "")
            # entries look like "A, B" or "A, B, C[auth D]"
            ids = []
            for tok in chunk.split(","):
                tok = tok.strip()
                if not tok:
                    continue
                if "[auth" in tok:
                    tok = tok.split("[auth", 1)[1].strip().rstrip("]").strip()
                ids.append(tok)
            chains = ids
        else:
            seq.append(line.strip())
    if chains is not None:
        out.append((chains, "".join(seq)))
    return out


def seq_for_chain(entities: list[tuple[list[str], str]], chain: str) -> str:
    for ids, seq in entities:
        if chain in ids:
            return seq
    raise KeyError(f"chain {chain} not found in RCSB FASTA (chains seen: "
                   f"{[i for ids, _ in entities for i in ids]})")


def write_fastas(pdb_id: str, rec: str, pep: str) -> None:
    SEQUENCES.mkdir(parents=True, exist_ok=True)
    (SEQUENCES / f"{pdb_id}_receptor.fasta").write_text(f">{pdb_id}_receptor\n{rec}\n")
    (SEQUENCES / f"{pdb_id}_peptide.fasta").write_text(f">{pdb_id}_peptide\n{pep}\n")
    (SEQUENCES / f"{pdb_id}_complex.fasta").write_text(
        f">{pdb_id}_receptor\n{rec}\n>{pdb_id}_peptide\n{pep}\n")


def reduce_structure(cif_text: str, keep: list[str], out_path) -> dict:
    st = gemmi.cif.read_string(cif_text)
    st = gemmi.make_structure_from_block(st.sole_block())
    st.setup_entities()
    st.remove_alternative_conformations()
    st.remove_hydrogens()
    st.remove_ligands_and_waters()

    model = st[0]
    present = {ch.name for ch in model}
    missing = [c for c in keep if c not in present]
    if missing:
        raise KeyError(f"chains {missing} absent from coordinates "
                       f"(present: {sorted(present)}); try --source assembly")

    out = gemmi.Structure()
    out.name = st.name
    out.spacegroup_hm = st.spacegroup_hm
    out.cell = st.cell
    m = gemmi.Model("1")
    kept = {}
    for ch in model:
        if ch.name not in keep:
            continue
        nc = gemmi.Chain(ch.name)
        for res in ch.get_polymer():
            info = gemmi.find_tabulated_residue(res.name)
            if info and (info.is_amino_acid() or info.is_nucleic_acid()):
                nc.add_residue(res)
        if len(nc):
            m.add_chain(nc)
            kept[ch.name] = len(nc)
    out.add_model(m)
    out.setup_entities()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out.write_pdb(str(out_path))
    return kept


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="+", metavar="PDBID", help="restrict to these PDB IDs")
    ap.add_argument("--tier", nargs="+", type=int, help="restrict to these tiers")
    ap.add_argument("--source", choices=["entry", "assembly"], default="entry")
    ap.add_argument("--skip-existing", action="store_true")
    args = ap.parse_args()

    targets = select(load_targets(), args.only, args.tier)
    if not targets:
        print("no targets matched", file=sys.stderr)
        return 2

    NATIVES.mkdir(parents=True, exist_ok=True)
    rc = 0
    audit = []
    for t in targets:
        native_pdb = NATIVES / f"{t.pdb_id}_native.pdb"
        if args.skip_existing and native_pdb.exists():
            print(f"{t.pdb_id}: skip (exists)")
            continue
        try:
            entities = parse_rcsb_fasta(_get(RCSB_FASTA.format(pdb_id=t.pdb_id)))
            rec_seq = seq_for_chain(entities, t.native_receptor[0])
            pep_seq = seq_for_chain(entities, t.native_peptide[0])
            write_fastas(t.pdb_id, rec_seq, pep_seq)

            if args.source == "assembly":
                url = RCSB_ASSEMBLY_CIF.format(pdb_id=t.pdb_id, n=t.assembly_n)
            else:
                url = RCSB_ENTRY_CIF.format(pdb_id=t.pdb_id)
            keep = t.native_receptor + t.native_peptide
            kept = reduce_structure(_get(url), keep, native_pdb)

            resolved_pep = kept.get(t.native_peptide[0], 0)
            frac = resolved_pep / max(len(pep_seq), 1)
            if resolved_pep < 5 or frac < 0.5:
                verdict = "DROP: peptide mostly disordered"
            elif frac < 0.8:
                verdict = "CAUTION: partial peptide"
            else:
                verdict = "ok"
            warn = "" if verdict == "ok" else f"  !! {verdict} ({resolved_pep}/{len(pep_seq)} resolved)"
            print(f"{t.pdb_id}: rec {t.native_receptor[0]}={len(rec_seq)}aa  "
                  f"pep {t.native_peptide[0]}={len(pep_seq)}aa  native={kept}{warn}")
            audit.append({"pdb_id": t.pdb_id, "tier": t.tier, "topology": t.topology,
                          "seqres_pep_len": len(pep_seq), "resolved_pep_len": resolved_pep,
                          "resolved_frac": round(frac, 2), "resolved_rec_len": kept.get(t.native_receptor[0], 0),
                          "verdict": verdict})
        except Exception as e:  # noqa: BLE001 - report and continue
            rc = 1
            print(f"{t.pdb_id}: ERROR {type(e).__name__}: {e}", file=sys.stderr)
            audit.append({"pdb_id": t.pdb_id, "tier": t.tier, "topology": t.topology,
                          "seqres_pep_len": "", "resolved_pep_len": "", "resolved_frac": "",
                          "resolved_rec_len": "", "verdict": f"ERROR {type(e).__name__}"})

    if audit:
        ap_csv = NATIVES / "_audit.csv"
        with ap_csv.open("w", newline="", encoding="utf-8") as fh:
            wr = csv.DictWriter(fh, fieldnames=list(audit[0].keys()))
            wr.writeheader()
            wr.writerows(sorted(audit, key=lambda r: (r["tier"], r["pdb_id"])))
        print(f"\naudit -> {ap_csv}")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
